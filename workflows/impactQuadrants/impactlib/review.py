"""Review step: assessments + overrides -> placements/<slug>.yaml (quadrant_plot.py format).

Hand edits survive re-runs in two ways:
  1. overrides.yaml (in the work folder, or --overrides FILE) is applied on top of the
     model placements every time:
         repos:
           <slug>:
             facet-check:openapi-discovery: {x: 0.3, y: 0.7, label: "...", label_pos: left}
             facet-check:mcp-exposure: {hide: true}
         combined:
           facet-check:openapi-discovery: {label_pos: below}
  2. If you edit placements/<slug>.yaml directly, the next `review` compares it with the
     copy it generated last time (placements/.generated/) and saves the fields you changed
     into overrides.yaml before regenerating. A deleted point becomes {hide: true}.
"""
from __future__ import annotations

import copy
import json
from pathlib import Path

import yaml

from .rubric import quadrant

EDITABLE = ("label", "x", "y", "category", "label_pos", "dx", "dy", "color", "rationale")
HEADER = ("# Generated by `impact.py review`. Plot with: python3 quadrant_plot.py THIS_FILE\n"
          "# You may edit points here; the next review copies your changes into overrides.yaml.\n")


def load_overrides(path: Path) -> dict:
    d = yaml.safe_load(path.read_text()) if path.is_file() else None
    d = d or {}
    d.setdefault("repos", {}); d.setdefault("combined", {})
    d["repos"] = d["repos"] or {}; d["combined"] = d["combined"] or {}
    return d


def save_overrides(path: Path, d: dict) -> None:
    text = ("# Hand corrections applied on top of model placements by `impact.py review`.\n"
            "# Keys are repository slugs, then gap ids. See impactlib/review.py.\n")
    path.write_text(text + yaml.safe_dump(d, sort_keys=True, allow_unicode=True, width=100))


def capture_edits(current: dict, generated: dict) -> dict:
    """{gap_id: {field: value}} for fields that differ between the two placement files."""
    cur = {p.get("gap_id"): p for p in current.get("points") or [] if p.get("gap_id")}
    gen = {p.get("gap_id"): p for p in generated.get("points") or [] if p.get("gap_id")}
    edits = {}
    for gid, gp in gen.items():
        cp = cur.get(gid)
        if cp is None:
            edits[gid] = {"hide": True}
            continue
        diff = {k: cp[k] for k in EDITABLE if k in cp and cp.get(k) != gp.get(k)}
        if diff:
            edits[gid] = diff
    return edits


def chart_settings(cfg: dict, title: str) -> dict:
    return {"title": title, "x_label": "Effort to implement  \u2192",
            "y_label": "Impact on agent access  \u2192", "quadrants": dict(cfg["quadrants"]),
            "categories": dict(cfg["categories"])}


def build_points(assessment: dict, gapfile: dict, ov: dict, cfg: dict) -> list[dict]:
    gaps = {g["id"]: g for g in gapfile["gaps"]}
    pts = []
    for pl in assessment["placements"]:
        g = gaps.get(pl["gap_id"])
        if g is None:
            continue
        p = {"label": pl["fix_label"], "x": round(float(pl["x"]), 3), "y": round(float(pl["y"]), 3),
             "category": g["category"], "gap_id": g["id"], "check": g["label"],
             "rationale": pl["rationale"], "confidence": pl["confidence"]}
        if pl.get("high_variance"):
            p["high_variance"] = True
            p["spread"] = [pl.get("spread_x"), pl.get("spread_y")]
        o = ov.get(g["id"]) or {}
        if o.get("hide"):
            continue
        for k, v in o.items():
            if k in EDITABLE:
                p[k] = v
        if o:
            p["overridden"] = sorted(k for k in o if k in EDITABLE)
        p["quadrant"] = quadrant(float(p["x"]), float(p["y"]), cfg["quadrants"])
        pts.append(p)
    return pts


def review(run, cfg, work: Path, overrides_path: Path | None = None, log=print) -> list[Path]:
    opath = overrides_path or work / "overrides.yaml"
    overrides = load_overrides(opath)
    pdir, gdir = work / "placements", work / "placements" / ".generated"
    gdir.mkdir(parents=True, exist_ok=True)
    captured = 0
    for repo in run.repos:
        cur, gen = pdir / f"{repo.slug}.yaml", gdir / f"{repo.slug}.yaml"
        if cur.is_file() and gen.is_file():
            edits = capture_edits(yaml.safe_load(cur.read_text()) or {},
                                  yaml.safe_load(gen.read_text()) or {})
            if edits:
                slot = overrides["repos"].setdefault(repo.slug, {}) or {}
                for gid, d in edits.items():
                    slot.setdefault(gid, {}).update(d)
                overrides["repos"][repo.slug] = slot
                captured += len(edits)
    if captured or not opath.is_file():
        save_overrides(opath, overrides)
        if captured:
            log(f"captured {captured} hand edit(s) into {opath}")
    out = []
    for repo in run.repos:
        ap = work / "assess" / f"{repo.slug}.json"
        gp = work / "gaps" / f"{repo.slug}.json"
        if not ap.is_file():
            raise SystemExit(f"{ap} missing; run `impact.py assess` first")
        assessment, gapfile = json.loads(ap.read_text()), json.loads(gp.read_text())
        pts = build_points(assessment, gapfile, overrides["repos"].get(repo.slug) or {}, cfg)
        doc = chart_settings(cfg, f"{repo.display}: where to start")
        doc.update({"repo": repo.slug, "run": run.stamp, "backend": assessment["backend"],
                    "model": assessment["model"], "placeholder": assessment["placeholder"],
                    "rubric_version": assessment["rubric_version"]})
        if assessment["placeholder"]:
            doc["warning"] = "PLACEHOLDER placements from stub_defaults.yaml, not model output"
        doc["points"] = pts
        text = HEADER + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100)
        (pdir / f"{repo.slug}.yaml").write_text(text)
        (gdir / f"{repo.slug}.yaml").write_text(text)
        out.append(pdir / f"{repo.slug}.yaml")
    return out


def load_placements(work: Path, slugs: list[str]) -> dict[str, dict]:
    out = {}
    for s in slugs:
        p = work / "placements" / f"{s}.yaml"
        if not p.is_file():
            raise SystemExit(f"{p} missing; run `impact.py review` first")
        out[s] = yaml.safe_load(p.read_text()) or {}
    return out
