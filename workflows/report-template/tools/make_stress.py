#!/usr/bin/env python3
"""Write data/test-stress.yaml: many repos, checks and questions (synthetic).

Exercises every pagination path: verdict-mix continuation pages, check-grid
column blocks and row chunks, and competency questions over several pages.
"""
import random
from pathlib import Path
import yaml

random.seed(7)
root = Path(__file__).resolve().parents[1]
base = yaml.safe_load((root / "data" / "test-variable.yaml").read_text())
cats = [f"cat{i}" for i in range(1, 7)]
checks = []
for i in range(38):
    checks.append({"id": f"c{i+1:02d}", "label": f"check {i+1}", "category": cats[min(i // 7, 5)]})
syms = ["P", "~", "A", "B", "o", "?"]
repos = []
for r in range(30):
    run = [c["id"] for c in checks if random.random() > 0.15]
    nq = random.choice([0, 0, 2, 4, 7, 12])
    repos.append({
        "name": f"Stress repo {r+1:02d}" + (" with a much longer name" if r == 3 else ""),
        "url": f"https://r{r+1}.example.org/",
        "minutes": random.randint(3, 30),
        "verdicts": {c: random.choice(syms) for c in run},
        "questions": [{"id": f"R{r+1}-{k+1}", "grade": random.choice(["match", "partial", "ungraded", "no-answer"])} for k in range(nq)],
    })
base["categories"] = [{"id": c, "label": f"category {c[-1]}"} for c in cats]
base["checks"] = checks
base["repositories"] = repos
base["report"]["pdf_title"] = "Template test (stress)"
(root / "data" / "test-stress.yaml").write_text(
    "# SYNTHETIC STRESS TEST (generated by tools/make_stress.py)\n" + yaml.safe_dump(base, sort_keys=False, width=200))
print("wrote data/test-stress.yaml")
